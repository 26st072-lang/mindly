import {readFileSync,writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {concernPolicy as policy} from './concern-policy.mjs';
const rulesURL=new URL('../firestore.rules',import.meta.url),filterURL=new URL('../concern-filter.js',import.meta.url);
// The rules lexer treats curly quotes as delimiters, even inside a string.
const literal=value=>/[‘’']/.test(value)?JSON.stringify(value):"'"+value.replace(/\\/g,'\\\\').replace(/\r/g,'\\r').replace(/\n/g,'\\n')+"'";
const ruleMatch=pattern=>literal('(?s).*'+pattern+'.*');
const replace=(value,entries)=>entries.reduce((text,[pattern,replacement])=>text+`.replace(${literal(pattern)}, ${literal(replacement)})`,value);
export function concernOutputs(){
  const browser=`/* Generated by scripts/build-concern-filter.mjs. Edit scripts/concern-policy.mjs. */
(function(root){
  const policy=${JSON.stringify(policy)};
  const prepared=policy.prepare.map(([pattern,replacement])=>[new RegExp(pattern,'gu'),replacement]);
  const safe=policy.safe.map(pattern=>new RegExp(pattern,'gu'));
  const finish=policy.finish.map(([pattern,replacement])=>[new RegExp(pattern,'gu'),replacement]);
  const blocked=policy.blocked.slice(0,-1).map(pattern=>new RegExp(pattern,'u'));
  const question=new RegExp(policy.blocked.at(-1),'u');
  function hasAbuse(content){
    let value=String(content).toLowerCase();
    for(const [pattern,replacement] of prepared)value=value.replace(pattern,replacement);
    if(question.test(value))return true;
    for(const pattern of safe)value=value.replace(pattern,'');
    for(const [pattern,replacement] of finish)value=value.replace(pattern,replacement);
    return blocked.some(pattern=>pattern.test(value));
  }
  const filter=Object.freeze({hasAbuse,message:policy.message});
  if(typeof module!=='undefined'&&module.exports)module.exports=filter;
  else root.MindlyConcernFilter=filter;
})(globalThis);
`;
  // Rule functions have at most ten let bindings. Separate transforms also keep
  // the generated expressions small enough for the rules evaluation budget.
  const strip=policy.safe.map(pattern=>[pattern,'']);
  const safeTransforms=[];
  for(let start=0;start<strip.length;start+=12)safeTransforms.push(strip.slice(start,start+12));
  const safeFunctions=safeTransforms.map((entries,index)=>`    function concernSafe${index}(value) {\n      return ${replace('value',entries)};\n    }`).join('\n');
  const safeValue=safeTransforms.reduce((value,entries,index)=>`concernSafe${index}(${value})`,'prepared');
  const normalization=[];
  for(let start=0;start<policy.prepare.length;start+=24)normalization.push(policy.prepare.slice(start,start+24));
  const normalizationFunctions=normalization.map((entries,index)=>`    function concernNormalize${index}(value) {\n      return ${replace('value',entries)};\n    }`).join('\n');
  const prepared=normalization.reduce((value,entries,index)=>`concernNormalize${index}(${value})`,'content.lower()');
  const rules=`    // BEGIN GENERATED CONCERN POLICY
${normalizationFunctions}
    function concernPrepared(content) {
      return ${prepared};
    }
${safeFunctions}
    function concernLanguageAllowed(content) {
      let prepared = concernPrepared(content);
      let value = ${replace(safeValue,policy.finish)};
      return !prepared.matches(${ruleMatch(policy.blocked.at(-1))})
        && ${policy.blocked.slice(0,-1).map(pattern=>'!value.matches('+ruleMatch(pattern)+')').join('\n        && ')};
    }
    // END GENERATED CONCERN POLICY`;
  return {browser,rules};
}
export function buildConcernFilter(check=false){
  const {browser,rules}=concernOutputs();
  const before=readFileSync(rulesURL,'utf8');
  const after=before.replace(/    \/\/ BEGIN GENERATED CONCERN POLICY[\s\S]*?    \/\/ END GENERATED CONCERN POLICY/,()=>rules);
  if(after===before&&!before.includes(rules))throw Error('Missing concern policy markers');
  if(check){
    if(readFileSync(filterURL,'utf8').replace(/\r\n/g,'\n')!==browser||before.replace(/\r\n/g,'\n')!==after.replace(/\r\n/g,'\n'))throw Error('Run npm run build:filter to synchronize the client and server policy.');
  }else{writeFileSync(filterURL,browser);writeFileSync(rulesURL,after);}
}
if(process.argv[1]&&pathToFileURL(process.argv[1]).href===import.meta.url)buildConcernFilter(process.argv.includes('--check'));
